import { PDFDocument, StandardFonts, rgb } from "pdf-lib";
import { fullName, formatDate } from "@/lib/utils";

type ExportMember = {
  firstName: string;
  lastName: string;
  otherNames?: string | null;
  sex: string;
  assembly: string;
  contact?: string | null;
  photoUrl?: string | null;
  location?: string | null;
  motherName?: string | null;
  fatherName?: string | null;
  position?: string | null;
  status: string;
  dateBaptised?: Date | string | null;
  baptisedBy?: string | null;
  createdAt: Date | string;
};

async function fetchImageBytes(url: string) {
  const res = await fetch(url);
  if (!res.ok) return null;
  const contentType = res.headers.get("content-type") ?? "";
  const bytes = new Uint8Array(await res.arrayBuffer());
  return { bytes, contentType };
}

export async function buildMemberPdf(member: ExportMember) {
  const pdf = await PDFDocument.create();
  const page = pdf.addPage([595, 842]);
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);

  const primary = rgb(0.18, 0.19, 0.57);
  const gold = rgb(1, 0.87, 0);
  const text = rgb(0.07, 0.07, 0.07);

  page.drawRectangle({
    x: 0,
    y: 780,
    width: 595,
    height: 62,
    color: primary,
  });
  page.drawRectangle({
    x: 0,
    y: 775,
    width: 595,
    height: 5,
    color: gold,
  });

  page.drawText("Mamprobi Worship Center", {
    x: 40,
    y: 812,
    size: 16,
    font: bold,
    color: rgb(1, 1, 1),
  });
  page.drawText("Member Profile Export", {
    x: 40,
    y: 792,
    size: 11,
    font,
    color: rgb(0.95, 0.95, 0.95),
  });

  let y = 730;
  const name = fullName(member);

  if (member.photoUrl) {
    try {
      const image = await fetchImageBytes(member.photoUrl);
      if (image) {
        const embedded = image.contentType.includes("png")
          ? await pdf.embedPng(image.bytes)
          : await pdf.embedJpg(image.bytes);
        const dims = embedded.scale(0.35);
        page.drawImage(embedded, {
          x: 420,
          y: 640,
          width: Math.min(dims.width, 130),
          height: Math.min(dims.height, 130),
        });
      }
    } catch {
      // Photo optional in PDF
    }
  }

  page.drawText(name, {
    x: 40,
    y,
    size: 20,
    font: bold,
    color: primary,
  });
  y -= 36;

  const fields: Array<[string, string]> = [
    ["Sex", member.sex],
    ["Assembly", member.assembly],
    ["Status", member.status],
    ["Contact", member.contact || "—"],
    ["Location", member.location || "—"],
    ["Position", member.position || "—"],
    ["Mother", member.motherName || "—"],
    ["Father", member.fatherName || "—"],
    ["Date Baptised", formatDate(member.dateBaptised)],
    ["Baptised By", member.baptisedBy || "—"],
    ["Record Created", formatDate(member.createdAt)],
  ];

  for (const [label, value] of fields) {
    page.drawText(label, {
      x: 40,
      y,
      size: 10,
      font: bold,
      color: primary,
    });
    page.drawText(String(value), {
      x: 160,
      y,
      size: 10,
      font,
      color: text,
      maxWidth: 240,
    });
    y -= 24;
  }

  page.drawText("Generated by MWC Church Management System", {
    x: 40,
    y: 40,
    size: 8,
    font,
    color: rgb(0.4, 0.4, 0.4),
  });

  return Buffer.from(await pdf.save());
}
