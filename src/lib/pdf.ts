import { PDFDocument, StandardFonts, rgb, type PDFFont, type PDFPage } from "pdf-lib";
import {
  fullName,
  formatDate,
  formatMaritalStatus,
  formatYesNo,
} from "@/lib/utils";
import { memberFieldLabel } from "@/lib/validations/member";

type ExportMember = {
  title?: string | null;
  firstName: string;
  middleName?: string | null;
  lastName: string;
  sex: string;
  dateOfBirth?: Date | string | null;
  placeOfBirth?: string | null;
  phone?: string | null;
  email?: string | null;
  assembly: string;
  status: string;
  maritalStatus?: string | null;
  addressLine1?: string | null;
  gpsAddress?: string | null;
  hometown?: string | null;
  streetName?: string | null;
  city?: string | null;
  holyGhostBaptism?: boolean | null;
  dateOfHolySpiritBaptism?: Date | string | null;
  waterBaptism?: boolean | null;
  dateOfBaptism?: Date | string | null;
  dateOfConversion?: Date | string | null;
  dateOfJoining?: Date | string | null;
  placeOfBaptism?: string | null;
  officiatingMinisterBaptism?: string | null;
  officiatingMinisterDistrict?: string | null;
  communicant?: boolean | null;
  occupation?: string | null;
  educationLevel?: string | null;
  profile?: string | null;
  dedicated?: boolean | null;
  dedicationDate?: Date | string | null;
  dedicationOfficiatingMinister?: string | null;
  dedicationChurch?: string | null;
  photoUrl?: string | null;
  createdAt: Date | string;
};

async function fetchImageBytes(url: string) {
  const res = await fetch(url);
  if (!res.ok) return null;
  const contentType = res.headers.get("content-type") ?? "";
  const bytes = new Uint8Array(await res.arrayBuffer());
  return { bytes, contentType };
}

function display(value?: string | null) {
  return value?.trim() ? value : "—";
}

export async function buildMemberPdf(member: ExportMember) {
  const pdf = await PDFDocument.create();
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const primary = rgb(0.18, 0.19, 0.57);
  const gold = rgb(1, 0.87, 0);
  const text = rgb(0.07, 0.07, 0.07);
  const muted = rgb(0.4, 0.4, 0.4);

  let page = pdf.addPage([595, 842]);
  let y = 730;

  function drawHeader(target: PDFPage) {
    target.drawRectangle({
      x: 0,
      y: 780,
      width: 595,
      height: 62,
      color: primary,
    });
    target.drawRectangle({
      x: 0,
      y: 775,
      width: 595,
      height: 5,
      color: gold,
    });
    target.drawText("Mamprobi Worship Center", {
      x: 40,
      y: 812,
      size: 16,
      font: bold,
      color: rgb(1, 1, 1),
    });
    target.drawText("Member Profile Export", {
      x: 40,
      y: 792,
      size: 11,
      font,
      color: rgb(0.95, 0.95, 0.95),
    });
  }

  function ensureSpace(needed = 24) {
    if (y < 60 + needed) {
      page.drawText("Generated by MWC Church Management System", {
        x: 40,
        y: 32,
        size: 8,
        font,
        color: muted,
      });
      page = pdf.addPage([595, 842]);
      drawHeader(page);
      y = 750;
    }
  }

  function drawSection(title: string) {
    ensureSpace(36);
    y -= 8;
    page.drawText(title, {
      x: 40,
      y,
      size: 11,
      font: bold,
      color: primary,
    });
    y -= 18;
  }

  function drawField(label: string, value: string, fontFace: PDFFont = font) {
    ensureSpace();
    page.drawText(label, {
      x: 40,
      y,
      size: 10,
      font: bold,
      color: primary,
    });
    page.drawText(String(value || "—"), {
      x: 268,
      y,
      size: 10,
      font: fontFace,
      color: text,
      maxWidth: 287,
    });
    y -= 18;
  }

  function wrapLines(value: string, size: number, maxWidth: number) {
    const paragraphs = value.replace(/\r\n/g, "\n").split("\n");
    const lines: string[] = [];
    for (const paragraph of paragraphs) {
      const words = paragraph.trim() === "" ? [""] : paragraph.split(/\s+/);
      let current = "";
      for (const word of words) {
        const next = current ? `${current} ${word}` : word;
        if (font.widthOfTextAtSize(next, size) > maxWidth && current) {
          lines.push(current);
          current = word;
        } else {
          current = next;
        }
      }
      lines.push(current);
    }
    return lines;
  }

  function drawParagraph(label: string, value: string) {
    const body = value.trim() ? value : "—";
    const lines = wrapLines(body, 10, 515);
    ensureSpace(36);
    page.drawText(label, {
      x: 40,
      y,
      size: 10,
      font: bold,
      color: primary,
    });
    y -= 16;
    for (const line of lines) {
      ensureSpace(16);
      if (line) {
        page.drawText(line, {
          x: 40,
          y,
          size: 10,
          font,
          color: text,
        });
      }
      y -= 14;
    }
    y -= 4;
  }

  drawHeader(page);
  const name = fullName(member);

  if (member.photoUrl) {
    try {
      const image = await fetchImageBytes(member.photoUrl);
      if (image) {
        const embedded = image.contentType.includes("png")
          ? await pdf.embedPng(image.bytes)
          : await pdf.embedJpg(image.bytes);
        const dims = embedded.scale(0.28);
        page.drawImage(embedded, {
          x: 430,
          y: 640,
          width: Math.min(dims.width, 120),
          height: Math.min(dims.height, 120),
        });
      }
    } catch {
      // Photo optional in PDF
    }
  }

  page.drawText(name, {
    x: 40,
    y,
    size: 20,
    font: bold,
    color: primary,
  });
  y -= 28;

  const sections: Array<[string, Array<[string, string]>]> = [
    [
      "Personal",
      [
        [memberFieldLabel("title"), display(member.title)],
        [memberFieldLabel("sex"), member.sex === "FEMALE" ? "Female" : "Male"],
        [memberFieldLabel("dateOfBirth"), formatDate(member.dateOfBirth)],
        [memberFieldLabel("placeOfBirth"), display(member.placeOfBirth)],
        [
          memberFieldLabel("maritalStatus"),
          formatMaritalStatus(member.maritalStatus) || "—",
        ],
      ],
    ],
    [
      "Contact & address",
      [
        [memberFieldLabel("phone"), display(member.phone)],
        [memberFieldLabel("email"), display(member.email)],
        [memberFieldLabel("addressLine1"), display(member.addressLine1)],
        [memberFieldLabel("streetName"), display(member.streetName)],
        [memberFieldLabel("city"), display(member.city)],
        [memberFieldLabel("gpsAddress"), display(member.gpsAddress)],
        [memberFieldLabel("hometown"), display(member.hometown)],
      ],
    ],
    [
      "Church",
      [
        [
          memberFieldLabel("status"),
          member.status === "OFFICER" ? "Officer" : "Member",
        ],
        [
          memberFieldLabel("assembly"),
          member.assembly === "ENGLISH" ? "English" : "Local",
        ],
      ],
    ],
    [
      "Baptism & faith",
      [
        [
          memberFieldLabel("holyGhostBaptism"),
          formatYesNo(member.holyGhostBaptism) || "—",
        ],
        [
          memberFieldLabel("dateOfHolySpiritBaptism"),
          formatDate(member.dateOfHolySpiritBaptism),
        ],
        [
          memberFieldLabel("waterBaptism"),
          formatYesNo(member.waterBaptism) || "—",
        ],
        [memberFieldLabel("dateOfBaptism"), formatDate(member.dateOfBaptism)],
        [
          memberFieldLabel("dateOfConversion"),
          formatDate(member.dateOfConversion),
        ],
        [memberFieldLabel("dateOfJoining"), formatDate(member.dateOfJoining)],
        [memberFieldLabel("placeOfBaptism"), display(member.placeOfBaptism)],
        [
          memberFieldLabel("officiatingMinisterBaptism"),
          display(member.officiatingMinisterBaptism),
        ],
        [
          memberFieldLabel("officiatingMinisterDistrict"),
          display(member.officiatingMinisterDistrict),
        ],
        [memberFieldLabel("communicant"), formatYesNo(member.communicant) || "—"],
      ],
    ],
    [
      "Dedication",
      [
        [memberFieldLabel("dedicated"), formatYesNo(member.dedicated) || "—"],
        [memberFieldLabel("dedicationDate"), formatDate(member.dedicationDate)],
        [
          memberFieldLabel("dedicationOfficiatingMinister"),
          display(member.dedicationOfficiatingMinister),
        ],
        [
          memberFieldLabel("dedicationChurch"),
          display(member.dedicationChurch),
        ],
      ],
    ],
    [
      "Work & education",
      [
        [memberFieldLabel("occupation"), display(member.occupation)],
        [memberFieldLabel("educationLevel"), display(member.educationLevel)],
        ["Record created", formatDate(member.createdAt)],
      ],
    ],
  ];

  for (const [title, fields] of sections) {
    drawSection(title);
    for (const [label, value] of fields) {
      drawField(label, value);
    }
  }

  drawSection("Profile");
  drawParagraph(memberFieldLabel("profile"), member.profile ?? "");

  page.drawText("Generated by MWC Church Management System", {
    x: 40,
    y: 32,
    size: 8,
    font,
    color: muted,
  });

  return Buffer.from(await pdf.save());
}
